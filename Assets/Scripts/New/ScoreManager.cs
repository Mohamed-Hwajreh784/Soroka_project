// Use English for comments in the code
using UnityEngine;
using TMPro;
using System.Collections;

public class ScoreManager : MonoBehaviour
{
    public static ScoreManager Instance { get; private set; }

    [Header("Audio (Optional)")]
    public AudioSource audioSource;
    public AudioClip victorySound;

    [Header("UI Reference (Optional)")]
    [Tooltip("If unassigned, the script will automatically create a 3D TextMeshPro object in front of the VR camera.")]
    public TMP_Text finalScoreText;

    private int currentScore = 0;
    private int totalCoinsInScene = 0;
    private int collectedCoins = 0;
    private bool isGameActive = false;

    // Internal reference for auto-generated TMP object
    private TextMeshPro autoGeneratedTMP;

    void Awake()
    {
        if (Instance == null)
        {
            Instance = this;
        }
        else
        {
            Destroy(gameObject);
            return;
        }

        if (audioSource == null)
        {
            audioSource = GetComponent<AudioSource>();
        }
    }

    void Start()
    {
        HideScoreText();
    }

    /// <summary>
    /// Resets scores and state for a new auto-mode game session.
    /// </summary>
    public void ResetGame()
    {
        currentScore = 0;
        collectedCoins = 0;
        totalCoinsInScene = 0;
        isGameActive = false;
        HideScoreText();
    }

    /// <summary>
    /// Sets total coins count expected in current round and activates gameplay tracking.
    /// </summary>
    public void SetTotalCoins(int coinCount)
    {
        totalCoinsInScene = coinCount;
        collectedCoins = 0;
        currentScore = 0;
        isGameActive = (totalCoinsInScene > 0);
        HideScoreText();
    }

    public bool IsGameActive() => isGameActive;
    public int GetCurrentScore() => currentScore;
    public int GetCollectedCoins() => collectedCoins;

    /// <summary>
    /// Call when a coin is collected (+1 score).
    /// </summary>
    public void CoinCollected()
    {
        if (!isGameActive) return;

        collectedCoins++;
        currentScore++;

        Debug.Log($"<color=yellow>[ScoreManager] Coin collected! ({collectedCoins}/{totalCoinsInScene}) | Score: {currentScore}</color>");

        // Trigger victory flow when all spawned coins are collected
        if (collectedCoins >= totalCoinsInScene)
        {
            StartCoroutine(ShowFinalSummaryRoutine());
        }
    }

    /// <summary>
    /// Call when hitting an obstacle (Chair) or Virus (-1 score).
    /// </summary>
    public void SubtractScore(int amount = 1)
    {
        if (!isGameActive) return;

        currentScore -= amount;
        Debug.Log($"<color=red>[ScoreManager] Penalty applied! Score: {currentScore}</color>");
    }

    /// <summary>
    /// Handles victory audio, displays score summary in VR for exactly 4 seconds, and cleans up.
    /// </summary>
    private IEnumerator ShowFinalSummaryRoutine()
    {
        isGameActive = false;

        // 1. Play victory audio
        if (audioSource != null && victorySound != null)
        {
            audioSource.PlayOneShot(victorySound);
        }

        // 2. Complete report session in SpawnerManager
        SpawnerManager spawner = FindFirstObjectByType<SpawnerManager>();
        if (spawner != null)
        {
            spawner.CompleteAutoSession(currentScore, collectedCoins);
        }

        // 3. Display completion text floating in front of VR camera
        DisplayFinalScoreText();

        // 4. Hold message on screen for exactly 4 seconds
        yield return new WaitForSeconds(4.0f);

        // 5. Hide floating text & destroy active HUDs
        HideScoreText();

        if (spawner != null)
        {
            spawner.DestroyScoreHUD();
            spawner.ResetPlacementData();
        }

        if (SessionUIManager.Instance != null)
        {
            SessionUIManager.Instance.ClearCompletionMessage();
            SessionUIManager.Instance.DestroyDynamicHUD();
        }

        // 6. Return to Main Menu
        MenuController menuCtrl = FindFirstObjectByType<MenuController>();
        if (menuCtrl != null)
        {
            menuCtrl.ResetAndGoToMainMenu();
        }
    }

    /// <summary>
    /// Creates or updates text object 1.5m in front of the VR camera at eye level.
    /// </summary>
    public void DisplayFinalScoreText()
    {
        string scoreMessage = $"STAGE COMPLETED!\nFinal Score: {currentScore}\nCoins Collected: {collectedCoins}/{totalCoinsInScene}";

        Transform mainCam = Camera.main != null ? Camera.main.transform : null;
        Vector3 spawnPosition = Vector3.forward * 1.5f;
        Quaternion spawnRotation = Quaternion.identity;

        if (mainCam != null)
        {
            Vector3 forwardDir = mainCam.forward;
            forwardDir.y = 0;
            forwardDir.Normalize();

            spawnPosition = mainCam.position + (forwardDir * 1.5f);
            spawnPosition.y = mainCam.position.y;
            spawnRotation = Quaternion.LookRotation(spawnPosition - mainCam.position);
        }

        if (finalScoreText != null)
        {
            finalScoreText.transform.position = spawnPosition;
            finalScoreText.transform.rotation = spawnRotation;
            finalScoreText.text = scoreMessage;
            finalScoreText.gameObject.SetActive(true);
            finalScoreText.ForceMeshUpdate();
        }
        else
        {
            if (autoGeneratedTMP == null)
            {
                GameObject textObj = new GameObject("VR_FinalScoreText_Runtime");
                autoGeneratedTMP = textObj.AddComponent<TextMeshPro>();
                autoGeneratedTMP.fontSize = 5f;
                autoGeneratedTMP.alignment = TextAlignmentOptions.Center;
                autoGeneratedTMP.color = Color.yellow;
            }

            autoGeneratedTMP.transform.position = spawnPosition;
            autoGeneratedTMP.transform.rotation = spawnRotation;
            autoGeneratedTMP.text = scoreMessage;
            autoGeneratedTMP.gameObject.SetActive(true);
        }
    }

    /// <summary>
    /// Hides and resets any score text.
    /// </summary>
    public void HideScoreText()
    {
        if (finalScoreText != null)
        {
            finalScoreText.gameObject.SetActive(false);
        }

        if (autoGeneratedTMP != null)
        {
            autoGeneratedTMP.gameObject.SetActive(false);
        }
    }
}